function applyLang(l){
  lang = l; localStorage.setItem("lang", l);
  root.lang = l; root.dir = l === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const v = T[l][el.dataset.i18n]; if (v) el.textContent = v;
  });
  document.querySelectorAll("[data-ph]").forEach(el => el.placeholder = T[l].ph[el.dataset.ph]);
  document.getElementById("langBtn").textContent = l === "ar" ? "EN" : "عربي";
  document.title = l === "ar" ? "عبدالله يحيى | Full Stack developer" : "Abdalla Yhya | Full Stack Developer";
  startTyping();
}
function applyTheme(t){
  theme = t; localStorage.setItem("theme", t);
  root.dataset.theme = t;
  document.getElementById("themeBtn").textContent = t === "dark" ? "☀" : "🌙";
}

function startTyping(){
  clearTimeout(typer);
  const el = document.getElementById("typed"), roles = T[lang].roles;
  let r = 0, c = 0, del = false;
  (function tick(){
    const w = roles[r];
    el.textContent = w.slice(0, c);
    if (!del && c === w.length){ del = true; typer = setTimeout(tick, 1400); return; }
    if (del && c === 0){ del = false; r = (r + 1) % roles.length; }
    c += del ? -1 : 1;
    typer = setTimeout(tick, del ? 40 : 90);
  })();
}

